"""Nightly real-model smoke test (issue #457).

Exercises the whole play pipeline against a **real local model** — no fake
runtime anywhere — and fails with a *classified* verdict so a red nightly is
triageable from the job summary alone.

What a full run does
--------------------
1. **download** — fetch the smallest registry model (role ``starter``:
   Qwen3 4B Instruct Q4_K_M) unless the CI cache already holds it.
2. **checksum** — hash the on-disk file and compare it to the registry
   ``sha256``.  This runs on cache hits too, so a drifted or truncated cached
   file fails loudly instead of silently feeding a corrupt model to the smoke.
3. **runtime** — start llama-cpp-python's OpenAI-compatible server on the GGUF
   and start ``convsim-core`` wired to it (``CONVSIM_RUNTIME_ID=llama_cpp``).
4. **conversation** — create and start a session on the built-in
   ``behavioral_interview`` scenario (the NPC opening is authored scenario text,
   not a generation), then submit a scripted multi-turn player conversation.
   Every NPC *reply* is generated by the real model under the turn-output JSON
   schema.
5. **debrief** — end the session and generate the debrief, asserting a *scored*
   debrief comes back (non-empty rubric dimensions, numeric overall score,
   non-empty summary).
6. **budget** — compare measured latencies against the documented budgets
   scaled by ``--ci-hardware-factor``.

``convsim-core``'s turn endpoint is synchronous — it returns the completed NPC
turn in a single response rather than streaming ``npc.token`` events (token
streaming is added by the ``apps/api`` gateway, which is not exercised here).
The smoke therefore measures full end-to-end turn latency (which subsumes
time-to-first-token) against the ``full_response_ms`` budget.

Failure classification
----------------------
Every failure is attributed to one class, printed in a banner, written to the
JSON report (``failure_class``) and the GitHub step summary, and mapped to a
distinct exit code:

===========  ====  =======================================================
class        exit  meaning
===========  ====  =======================================================
``budget``      1  latency regression: the pipeline worked, just too slowly
``download``    2  model could not be fetched (network / HTTP / missing cache)
``checksum``    3  SHA-256 drift: on-disk bytes ≠ registry ``sha256``
``runtime``     4  llama-server or convsim-core crashed, hung, or 5xx'd
``pipeline``    5  servers healthy but an end-to-end assertion failed
``timeout``     6  wall-clock budget exhausted (phase named in the message)
===========  ====  =======================================================

Transcript content is fully scripted (see ``SCRIPTED_PLAYER_TURNS``) and holds
no user data, so short NPC excerpts are logged and reported — they are the
evidence that a real model, not a canned fallback, drove the conversation.
``save_transcript`` is false, so no transcript file is written.

Usage
-----
Resolve the starter model from the registry (writes ``$GITHUB_OUTPUT``)::

    python scripts/nightly-model-smoke.py --print-registry-model starter

Download only (cache miss)::

    python scripts/nightly-model-smoke.py --download-only \\
        --model-id <id> --model-url <url> --model-sha256 <hex>

Verify an already-cached file without running the smoke::

    python scripts/nightly-model-smoke.py --verify-only \\
        --model-id <id> --model-sha256 <hex>

Full smoke::

    python scripts/nightly-model-smoke.py \\
        --model-id qwen3-4b-instruct-q4_k_m \\
        --model-sha256 <hex> \\
        --ci-hardware-factor 20 \\
        --wall-clock-budget-s 1200 \\
        --report-path /tmp/smoke-report.json
"""

