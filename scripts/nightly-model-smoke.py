def _assert_port_free(port: int, label: str) -> None:
    """Refuse to run when something already listens on ``port``.

    Readiness is a URL poll, and a squatter answers it.  The child we spawned
    loses the bind and exits, but it is still starting up when the first poll
    runs — ``llama_cpp.server`` loads the whole GGUF before it binds — so the
    poll succeeds against the *foreign* server and ``_wait_for_http`` returns
    happy.  Nothing downstream catches it either: ``_crashed_child`` is only
    consulted once a ``SmokeFailure`` has been raised, so a run that otherwise
    goes green never notices that the process it started is dead.

    The result is the one verdict this job must never return: a pass earned by
    a model whose bytes it never checksum-verified, on a runtime it did not
    choose.  CI runners are clean, so this is about the local repro in
    docs/real-model-smoke.md — which is also how the real-model path gets
    verified by hand, since no PR job can exercise it.
    """
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(1.0)
        if sock.connect_ex(("127.0.0.1", port)) != 0:
            return
    raise SmokeFailure(
        FailureClass.RUNTIME,
        f"Port {port} is already in use, so {label} cannot be started on it",
        # Not the class remedy: it says to read the child's stderr tail, and no
        # child has been started yet.
        remedy=(
            f"Stop whatever is listening on 127.0.0.1:{port}, then re-run. The smoke "
            f"has to own {label}: readiness is a URL poll, so a server it did not "
            "start answers it and the run would pass on a model these bytes were "
            "never verified against."
        ),
    )


def _start_llama_server(model_path: Path, port: int) -> subprocess.Popen:
    """Start llama-cpp-python's OpenAI-compatible server on the given port.

    convsim-core's ``llama_cpp`` runtime adapter talks to this server over
    ``/v1/chat/completions`` (see services/convsim-core/.../runtime/llama_cpp.py).
    """
    return subprocess.Popen(
        [sys.executable, "-m", "llama_cpp.server",
         "--model", str(model_path),
         "--host", "127.0.0.1", "--port", str(port),
         "--n_ctx", "8192"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )


def _start_core(data_dir: Path, port: int, llama_port: int, llama_timeout_s: float) -> subprocess.Popen:
    """Start convsim-core wired to the local llama-server via env overrides."""
    env = os.environ.copy()
    env.update({
        # Select the real llama.cpp runtime (default is the deterministic fake).
        "CONVSIM_RUNTIME_ID": "llama_cpp",
        # Point the adapter at the llama-server started above.
        "CONVSIM_LLAMA_CPP_BASE_URL": f"http://127.0.0.1:{llama_port}",
        "CONVSIM_LLAMA_CPP_CONTEXT_LENGTH": "8192",
        # The adapter's generation timeout must outlast the slowest call we
        # intend to measure (the debrief), or a slow-but-reportable generation
        # on the 2-vCPU CPU-only runner is killed before we can time it and
        # convsim-core answers 500 — a latency problem misfiled as a RUNTIME
        # crash, failing the nightly spuriously instead of reporting the real
        # latency.  See run_smoke.  CHAT_TIMEOUT is the one that bounds
        # /v1/chat/completions; TIMEOUT only covers model listing, and is
        # raised alongside it so a cold first listing on a loaded runner is not
        # cut short either.
        "CONVSIM_LLAMA_CPP_CHAT_TIMEOUT": str(int(llama_timeout_s)),
        "CONVSIM_LLAMA_CPP_TIMEOUT": str(int(llama_timeout_s)),
        "CONVSIM_DATA_DIR": str(data_dir),
        "CONVSIM_LOG_DIR": str(data_dir / "logs"),
        "CONVSIM_DB_DIR": str(data_dir / "db"),
        "CONVSIM_PACKS_DIR": str(data_dir / "packs"),
        "CONVSIM_PORT": str(port),
        "CONVSIM_HOST": "127.0.0.1",
    })
    return subprocess.Popen(
        [sys.executable, "-m", "uvicorn", "convsim_core.main:app",
         "--host", "127.0.0.1", "--port", str(port), "--log-level", "warning"],
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )


def _wait_for_http(url: str, timeout_s: float, label: str, proc: Optional[subprocess.Popen] = None) -> None:
    """Poll ``url`` until it answers, or raise a RUNTIME failure.

    When ``proc`` is given, an exited child short-circuits the wait: a crashed
    server is a runtime failure we can name immediately rather than something to
    keep polling for until the timeout.
    """
    deadline = time.monotonic() + timeout_s
    last_err: Optional[Exception] = None
    while time.monotonic() < deadline:
        if proc is not None and proc.poll() is not None:
            raise SmokeFailure(
                FailureClass.RUNTIME,
                f"{label} exited with code {proc.returncode} before becoming ready",
            )
        try:
            with urllib.request.urlopen(url, timeout=5):
                return
        except urllib.error.HTTPError:
            # A response (even 4xx) means the server is up and routing.
            return
        except Exception as exc:  # noqa: BLE001 — connection refused while booting
            last_err = exc
            time.sleep(1)
    raise SmokeFailure(
        FailureClass.RUNTIME,
        # !r, like every other error this file reports: str() on an exception
        # raised with no arguments is the empty string, so a readiness failure
        # whose last error was e.g. a bare ConnectionRefusedError rendered as
        # "did not become ready within 300 s ()" — no diagnostic at all in the
        # one message a `runtime` verdict leaves behind.
        f"{label} did not become ready within {timeout_s:.0f} s ({last_err!r})",
    )


# ── HTTP helpers (every transport-level failure is a RUNTIME failure) ──────────


def _request_json(
    url: str,
    *,
    payload: Optional[dict] = None,
    timeout: float,
    expect: Sequence[int] = (200, 201),
) -> dict:
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json"} if data is not None else {},
        method="POST" if data is not None else "GET",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = json.loads(resp.read())
            if resp.status not in expect:
                raise SmokeFailure(
                    FailureClass.PIPELINE,
                    f"{url} returned HTTP {resp.status}, expected one of {list(expect)}",
                )
            return body
    except urllib.error.HTTPError as exc:
        detail = exc.read(2048).decode(errors="replace")
        # 5xx is the server breaking; 4xx is the server rejecting what we asked
        # for, i.e. an end-to-end assertion about the API contract.
        cls = FailureClass.RUNTIME if exc.code >= 500 else FailureClass.PIPELINE
        raise SmokeFailure(cls, f"{url} returned HTTP {exc.code}: {detail[:500]}") from exc
    except SmokeFailure:
        raise
    except Exception as exc:  # noqa: BLE001 — connection reset, timeout, bad JSON
        raise SmokeFailure(
            FailureClass.RUNTIME,
            f"{url} did not answer with usable JSON after {timeout:.0f} s: {exc!r}",
        ) from exc


def _npc_turn_payload(events: Sequence[dict]) -> Dict[str, Any]:
    """Return the NPC event's payload from a turn/start response, or ``{}``."""
    for ev in events:
        if ev.get("event_type") in ("npc_turn", "npc_opening"):
            payload = ev.get("payload")
            return payload if isinstance(payload, dict) else {}
    return {}


def _npc_turn_content(events: Sequence[dict]) -> str:
    """Return the NPC utterance from a turn/start response's events, or ''."""
    content = _npc_turn_payload(events).get("content", "")
    return content if isinstance(content, str) else ""


def _rubric_observation_count(events: Sequence[dict]) -> Optional[int]:
    """Count the rubric observations the model volunteered on this NPC turn.

    The turn response carries the *validated* observations, which is the only
    way to tell the two causes of an unscored debrief apart: the debrief engine
    re-derives its dimension scores from each NPC turn's stored raw model output
    (``_parse_rubric_observations`` in debrief_engine.py), so observations that
    were accepted on the turn but never scored mean the debrief engine lost
    them, while no observations anywhere means the model simply never
    volunteered any.  See ``evaluate_debrief``.

    Returns ``None`` — not 0 — when the payload carries no readable
    ``rubric_observations`` list, the same way the per-turn parse flags warn
    rather than pass when the debug endpoint gives us nothing: "the model
    volunteered none" and "we could not read what it volunteered" lead to
    opposite triage, and the whole point of recording this is that the
    unscored-debrief verdict names a cause it has actually established.  An
    empty list is a real observation of zero and still counts as 0.
    """
    observations = _npc_turn_payload(events).get("rubric_observations")
    return len(observations) if isinstance(observations, list) else None


def _total_rubric_observations(turns: Sequence[Dict[str, Any]]) -> Optional[int]:
    """Total the per-turn rubric observation counts, or ``None`` if unknowable.

    ``None`` means *the sum cannot be trusted as a total*, which is not the same
    as "nothing was readable":

    * a total above zero is conclusive even with an unreadable turn among the
      readable ones — observations *were* seen, so the debrief losing them is
      the cause whatever the missing turn carried;
    * a sum of zero is only conclusive when every generated turn was readable.
      With counts of ``[0, None, 0]`` two turns really did carry nothing, but
      reporting 0 would have the verdict assert the model volunteered nothing
      across the conversation when the turn it could not read may have carried
      plenty — so that case is ``None`` too, and the report's per-turn
      ``rubric_observation_count`` shows which turn was the unreadable one;
    * no generated turn at all is ``None``: there was nothing to read.

    Only the authored opening is skipped: it is not a generation and so has no
    count to miss.
    """
    counts = [
        t.get("rubric_observation_count") for t in turns if t.get("model_generated")
    ]
    total = sum(c for c in counts if isinstance(c, int))
    if total > 0:
        return total
    zero_is_unreliable = not counts or any(not isinstance(c, int) for c in counts)
    return None if zero_is_unreliable else 0


def _collapse(text: str) -> str:
    """Normalise whitespace so two utterances can be compared as written."""
    return " ".join(text.split())


def _excerpt(text: str) -> str:
    collapsed = _collapse(text)
    return collapsed[:EXCERPT_CHARS] + ("…" if len(collapsed) > EXCERPT_CHARS else "")


def _excerpt_any(value: Any) -> str:
    """Excerpt a server-supplied value that *should* be a string, whatever it is.

    ``_excerpt`` calls ``str.split``, so handing it a non-string raises
    ``AttributeError``.  Where that value came out of a convsim-core response —
    the debrief summary is the one such field the harness both excerpts into the
    report and asserts on — the raise escapes into ``run_smoke``'s catch-all and
    reports a changed product response contract as "most likely a bug in the
    smoke harness", which is the one thing it is certainly not.

    ``repr`` rather than ``str``, so the artifact shows the shape that arrived
    instead of a coerced empty string.  Telling the run it is *wrong* stays
    ``evaluate_debrief``'s job: a dict's repr is easily long enough to satisfy
    the summary length check, so nothing here may be mistaken for acceptance.
    """
    if value is None:
        return ""
    return _excerpt(value if isinstance(value, str) else repr(value))


def _replays_opening(npc_text: str, opening_text: str) -> bool:
    """True when an NPC reply opens by reciting the authored opening verbatim.

    The scenario's opening line sits in the transcript the turn prompt renders,
    and the starter model can answer a player turn by copying it back: all ten
    nightly runs of the previous single-turn harness still in GitHub's log
    retention logged an NPC reply whose leading characters matched
    ``opening_npc_says`` exactly.  That is not a reply, but nothing downstream
    notices — the utterance is non-empty and it is not
    ``SAFE_FALLBACK_UTTERANCE``, so ``used_fallback`` stays false and the
    per-turn parse flags report a healthy turn.  Proving the turns are real
    therefore needs this check as well as those flags.

    Those ten runs are evidence that the failure mode exists, not that it is the
    norm: the player turn they submitted was "Reply with exactly one sentence:
    Hello, I am ready." — an instruction to the model, not something an
    interview candidate says — and this harness replaces it with the
    in-character ``SCRIPTED_PLAYER_TURNS``, which the real starter model
    answered properly in local verification.  So the expected rate here is zero
    and the warning is worth reading when it fires, rather than a known
    condition to scroll past.

    A *leading prefix* match, not equality and not the whole opening: a recital
    that then carries on into fresh prose is the same regurgitation, and a
    recital that veers off partway through the opening is too — see
    ``REPLAY_PREFIX_CHARS`` for why the latter matters and where the length
    comes from.  No legitimate reply begins by reading the opening question
    back out.
    """
    opening = _collapse(opening_text)
    if not opening:
        return False
    threshold = min(len(opening), REPLAY_PREFIX_CHARS)
    return _collapse(npc_text)[:threshold] == opening[:threshold]


# ── Assertions (pure, unit-tested) ────────────────────────────────────────────


def _all_generated_turns_fell_back(turns: Sequence[Dict[str, Any]]) -> bool:
    """True when every model-generated turn returned the canned safe utterance.

    Two verdicts turn on this and they must agree: ``evaluate_turns`` fails the
    run for it, and ``evaluate_debrief`` uses it to say that an unscored debrief
    is downstream of those fallbacks rather than evidence about rubric
    prompting.  One of them deciding "all of them" while the other decides "not
    quite all" would put both notes in the same verdict, each telling the reader
    the other is the wrong place to start.

    False when there are no generated turns (``evaluate_turns`` reports that
    separately) and when the parse flags were unavailable, since an absent
    ``used_fallback`` is not a fallback.
    """
    generated = [t for t in turns if t.get("model_generated")]
    return bool(generated) and all(t.get("used_fallback") for t in generated)


def evaluate_turns(turns: List[Dict[str, Any]]) -> tuple[List[str], List[str]]:
    """Check the conversation really came from the model.  Returns (failures, warnings).

    The fallback policy is applied only to turns marked ``model_generated``: the
    NPC opening is authored scenario text, so counting it would make the
    "every turn fell back" check unreachable.

    An empty NPC utterance is always a failure.  A single fallback turn is a
    warning — a 4 B model does occasionally emit output the validator rejects,
    and the product's job is to recover from that — but if *every* generated turn
    fell back to the canned safe utterance then no real NPC turns were produced
    and the smoke proved nothing, so that is a failure.

    Turns carrying no ``used_fallback`` flag at all — the debug endpoint is
    best-effort — warn that the check did not run, so an absent proof is not
    mistaken for a passed one.

    ``replayed_opening`` gets the identical policy for the other way a turn can
    pass every flag without being a reply: reciting the authored opening back at
    the player (see ``_replays_opening``).  Unlike the parse flags this is
    computed from the response the harness already holds, so it is never
    missing.

    The two policies also have to compose: a conversation split between them —
    one turn recites, the rest fall back — trips neither "all of them" check
    while still containing no reply, so a run with no turn that is both real
    output *and* an answer fails as well.
    """
    failures: List[str] = []
    warnings: List[str] = []
    if not turns:
        return (["No turns were recorded; the conversation never ran"], warnings)

    for turn in turns:
        label = turn.get("label", f"turn {turn.get('turn_number')}")
        if not turn.get("npc_excerpt"):
            failures.append(f"{label}: completed but returned no NPC utterance")

    generated = [t for t in turns if t.get("model_generated")]
    if not generated:
        failures.append("No model-generated NPC turns were recorded")
        return (failures, warnings)

    if not any("used_fallback" in t for t in generated):
        # The flags come from the debug endpoint, which is best-effort. Without
        # them a canned fallback is indistinguishable from real model output —
        # it is a non-empty NPC utterance too — so the check below silently
        # passes. Say so, rather than let the report imply a proof we do not have.
        warnings.append(
            "Per-turn parse flags were unavailable, so the fallback check did not "
            "run: this run cannot prove the NPC turns were model output rather "
            "than the canned safe utterance"
        )

    fallbacks = [t for t in generated if t.get("used_fallback")]
    all_fell_back = _all_generated_turns_fell_back(turns)
    if all_fell_back:
        failures.append(
            f"All {len(generated)} model-generated NPC turns fell back to the canned "
            "safe utterance; the real model produced no usable turn output"
        )
    elif fallbacks:
        warnings.append(
            f"{len(fallbacks)} of {len(generated)} model-generated NPC turns fell back "
            "to the safe utterance"
        )

    # Same policy as the fallback check above, for the other way a turn can look
    # real without being one: reciting the authored opening back instead of
    # answering.  See _replays_opening — the parse flags cannot see this, so
    # without it "the model produced real NPC turns" rests on the utterance
    # merely being non-empty.
    echoes = [t for t in generated if t.get("replayed_opening")]
    if echoes and len(echoes) == len(generated):
        failures.append(
            f"All {len(generated)} model-generated NPC turns began by reciting the "
            "authored opening line back at the player; the model answered no player "
            "turn, so this run proves nothing about real NPC replies"
        )
    elif echoes:
        warnings.append(
            f"{len(echoes)} of {len(generated)} model-generated NPC turns began by "
            "reciting the authored opening line back at the player instead of "
            "answering them: real output, but not a reply. Recurring in the same turn "
            "position every night is a turn-prompt problem, not an unlucky sample"
        )

    # Neither check above fires when the generated turns are *split* between the
    # two anomalies — one recites the authored opening, the others fall back —
    # and that conversation contains no NPC reply at all.  Each check warns
    # rather than fails on its own because a run that recovers from one bad turn
    # is the product working; the union of them leaves nothing that recovered,
    # which is the failure both checks exist to catch, so it has to fail too.
    # Reachable in practice: the previous harness logged a recited opening on
    # the first player turn every night, and a 4 B model does occasionally emit
    # output the validator rejects on the rest.
    mixed = not all_fell_back and len(echoes) != len(generated)
    if mixed and not [
        t
        for t in generated
        if not t.get("used_fallback") and not t.get("replayed_opening")
    ]:
        failures.append(
            f"Not one of the {len(generated)} model-generated NPC turns was a reply: "
            f"{len(fallbacks)} fell back to the canned safe utterance and "
            f"{len(echoes)} began by reciting the authored opening line. Neither "
            "count alone would fail the run, but between them they account for "
            "every generated turn, so no player turn was answered and this run "
            "proves nothing about real NPC replies"
        )
    return (failures, warnings)


def evaluate_debrief(
    debrief: Optional[Dict[str, Any]],
    *,
    rubric_observations_seen: Optional[int] = None,
    turns_all_fell_back: bool = False,
) -> tuple[List[str], List[str]]:
    """Check that a *scored* debrief was produced.  Returns (failures, warnings).

    "Scored" is the #457 acceptance criterion, so an unscored debrief is a
    failure — but on its own that failure does not say which of several very
    different things happened, and the remedy differs completely.
    ``rubric_observations_seen`` (how many rubric observations the NPC turns
    actually returned, ``None`` when the run could not read any — see
    ``_total_rubric_observations``) and ``turns_all_fell_back`` resolve it:

    * **0, every generated turn fell back** — the turns carried no observations
      because they carried no model output at all. Not evidence about rubric
      prompting; a consequence of the fallback failure ``evaluate_turns``
      already reported: ``UNSCORED_AFTER_FALLBACK_NOTE``.
    * **0, turns that did not fall back** — the model volunteered nothing to
      score, which nothing asked it to. Reachable because of the thin prompt
      coverage, but not the normal outcome (the real starter model volunteers
      observations on every turn), so still worth chasing:
      ``UNSCORED_DEBRIEF_NOTE``.
    * **> 0** — the turns carried observations and the debrief lost them. A real
      regression with a named starting point: ``UNSCORED_WITH_OBSERVATIONS_NOTE``.

    Without that count the failure can only quote both possibilities and send
    the reader to the previous nightly's artifact to tell them apart, which is
    the one piece of triage this harness is meant to have already done.
    """
    failures: List[str] = []
    warnings: List[str] = []
    if not debrief:
        return (["No debrief was produced"], warnings)

    scores = debrief.get("scores")
    if not isinstance(scores, dict) or not scores:
        if rubric_observations_seen:
            cause = (
                f"the NPC turns returned {rubric_observations_seen} rubric "
                "observation(s), so the debrief engine had something to accumulate "
                "and did not. "
            ) + UNSCORED_WITH_OBSERVATIONS_NOTE
        elif rubric_observations_seen == 0 and turns_all_fell_back:
            cause = (
                "no NPC turn carried a rubric_observation, so the debrief engine "
                "had nothing to accumulate — but none of them carried any model "
                "output either. "
            ) + UNSCORED_AFTER_FALLBACK_NOTE
        elif rubric_observations_seen == 0:
            cause = (
                "no NPC turn carried a rubric_observation, so the debrief engine "
                "had nothing to accumulate. "
            ) + UNSCORED_DEBRIEF_NOTE
        else:
            # Neither cause can be ruled out, so quote both rather than pick
            # one: asserting the model volunteered nothing, on the one branch
            # that just said it could not tell, is the triage this harness is
            # supposed to have done, done wrongly.
            cause = (
                "at least one NPC turn's rubric_observations list was "
                "unreadable and the turns that were readable carried none, so "
                "the run cannot claim the model volunteered nothing and the two "
                "causes below cannot be told apart from this message — read "
                "rubric_observation_count per turn in the report artifact (null "
                "marks the unreadable turns, which is itself worth a look at the "
                "turn response contract). " + UNSCORED_DEBRIEF_NOTE
                + " If the turns did carry observations, it is the other cause "
                "instead: " + UNSCORED_WITH_OBSERVATIONS_NOTE
            )
        failures.append(f"Debrief has no rubric dimension scores: {cause}")

    overall = debrief.get("overall_score")
    if not isinstance(overall, (int, float)) or isinstance(overall, bool):
        failures.append(f"Debrief overall_score is not numeric (got {overall!r})")
    elif not 0 <= overall <= 100:
        failures.append(f"Debrief overall_score {overall} is outside [0, 100]")

    summary = debrief.get("summary")
    if summary is not None and not isinstance(summary, str):
        # Checked as a type before it is measured as a length, for the same
        # reason _rubric_observation_count returns None rather than 0 for an
        # unreadable list: len(summary.strip()) raises AttributeError here, and
        # an AttributeError out of the assertion layer lands in run_smoke's
        # catch-all as "most likely a bug in the smoke harness" — the one
        # verdict that is certainly wrong when it is the product's own response
        # contract that changed.  A debrief whose summary is not text is a
        # `pipeline` failure like any other output the product rejects.
        failures.append(
            f"Debrief summary is not a string (got {type(summary).__name__}): "
            f"{_excerpt_any(summary)}"
        )
    elif len((summary or "").strip()) < MIN_SUMMARY_CHARS:
        failures.append(
            f"Debrief summary is shorter than {MIN_SUMMARY_CHARS} characters "
            f"({len((summary or '').strip())} chars)"
        )

    if debrief.get("used_fallback"):
        # Not a failure: the scores — the thing #457 asks this job to assert —
        # come from the per-turn rubric observations, not from this generation,
        # so a template narrative degrades the debrief rather than invalidating
        # the run, and one unlucky generation must not red the nightly.
        #
        # But the debrief is generated exactly once, so a fallback means *no*
        # model-written debrief prose was produced at all, and this is the only
        # job that would ever notice.  Say what the otherwise-green verdict
        # therefore does not prove, rather than just naming the flag.
        warnings.append(
            "Debrief narrative used the deterministic fallback, not model prose: "
            "the model's debrief output failed validation and the repair pass, so "
            "this run exercised the scoring path but proves nothing about "
            "real-model debrief generation. Recurring across nightlies means a "
            "regression in the debrief prompt or DEBRIEF_NARRATIVE_SCHEMA rather "
            "than one unlucky generation"
        )
    if not debrief.get("turning_points"):
        warnings.append("Debrief contains no turning points")
    return (failures, warnings)


def evaluate_budgets(
    measured_ms: Dict[str, float],
    ci_hardware_factor: float,
    budgets_ms: Dict[str, int] = BUDGETS_MS,
    tolerance: float = REGRESSION_TOLERANCE,
) -> tuple[List[str], List[str]]:
    """Compare measurements to scaled budgets.  Returns (failures, report_lines)."""
    failures: List[str] = []
    lines: List[str] = []
    for key, budget_ms in budgets_ms.items():
        measured = measured_ms.get(key)
        if measured is None:
            continue
        ci_budget = budget_ms * ci_hardware_factor
        ceiling = ci_budget * tolerance
        status = "PASS" if measured <= ceiling else "FAIL"
        lines.append(
            f"{key}: {measured:.0f} ms "
            f"(CI budget {ci_budget:.0f} ms × {tolerance} = {ceiling:.0f} ms) → {status}"
        )
        if status == "FAIL":
            failures.append(
                f"{key} = {measured:.0f} ms exceeds CI ceiling {ceiling:.0f} ms "
                f"(documented budget {budget_ms} ms × {ci_hardware_factor} × {tolerance})"
            )
    return (failures, lines)


def timeout_latency_evidence(
    turns: Sequence[Dict[str, Any]], ceiling_ms: float
) -> Optional[str]:
    """Name the latency regression hiding inside a ``timeout`` verdict, if there is one.

    The wall-clock budget and the latency ceiling sit close together by
    construction: three scripted turns at the CI ceiling (240 s each) plus a
    debrief allowed twice that very nearly fill the 20 min budget.  So a uniform
    slowdown large enough to fail the budget check usually exhausts the clock
    *before* the budget phase runs, and TIMEOUT — which outranks everything but
    a crashed child — is what gets reported.  That class is honest, the clock
    did run out, but its remedy ("inference got much slower or a phase hung")
    leaves the reader to work out which.  When the turns that *did* complete are
    already past the ceiling, we know which, so say so.

    Returns ``None`` when the completed turns were inside the ceiling (a genuine
    hang, or a phase other than the conversation ran long) or when no
    model-generated turn finished at all.
    """
    latencies = [
        float(t["latency_ms"])
        for t in turns
        if t.get("model_generated") and isinstance(t.get("latency_ms"), (int, float))
    ]
    if not latencies:
        return None
    median_ms = statistics.median(latencies)
    if median_ms <= ceiling_ms:
        return None
    return (
        f"The {len(latencies)} NPC turn(s) that did complete have a median latency of "
        f"{median_ms:.0f} ms, already past the {ceiling_ms:.0f} ms CI ceiling: this is "
        "most likely the latency regression `budget` exists to catch rather than a "
        "hung phase. Compare measured_ms in the report artifact against recent "
        "nightlies before raising --wall-clock-budget-s."
    )


