class StderrTail:
    """The most recent lines of a child's stderr, safe to read while it writes.

    A bare ``deque`` is the obvious container and the wrong one.  The draining
    thread keeps appending for as long as the child is alive, and the tails are
    dumped from ``run_smoke``'s *except* handler — before the ``finally`` block
    stops either child — so the reader and the writer genuinely overlap.
    Iterating a deque another thread is appending to raises
    ``RuntimeError: deque mutated during iteration``, which would escape the
    handler and throw away the classified verdict it had just assembled: the
    same way an already-exhausted ``Deadline.finish()`` once turned a
    reportable timeout into a bare traceback.  And it would do it on exactly
    the failures where the child is still talking — a timeout whose abandoned
    generation is still running, a 5xx being logged.

    So appends and reads take a lock, and readers get a snapshot rather than a
    live view of the buffer.
    """

    def __init__(self, maxlen: int = 200) -> None:
        self._lines: deque = deque(maxlen=maxlen)
        self._lock = threading.Lock()

    def append(self, line: str) -> None:
        with self._lock:
            self._lines.append(line)

    def snapshot(self) -> List[str]:
        with self._lock:
            return list(self._lines)


def _drain(stream: object, sink: Optional[StderrTail] = None) -> None:
    """Consume a subprocess pipe in the background to avoid a full-buffer deadlock.

    When ``sink`` is given, the most recent lines are retained so they can be
    surfaced if the smoke fails.  The child's stderr is otherwise discarded,
    which makes a server-side 500 undiagnosable from the CI logs — the client
    only ever sees ``HTTPError: 500`` with no server traceback.
    """
    try:
        for raw in stream:  # type: ignore[attr-defined]
            if sink is not None:
                line = raw.decode(errors="replace") if isinstance(raw, bytes) else raw
                sink.append(line.rstrip("\n"))
    except Exception:
        pass


def _dump_stderr_tails(tails: Sequence[tuple[str, StderrTail]]) -> None:
    for label, tail in tails:
        # One snapshot, used for both the count and the lines: reading the
        # length separately would let the header promise more lines than the
        # dump prints while the child is still writing.
        lines = tail.snapshot()
        if lines:
            print(f"\n[smoke] ── {label} stderr (last {len(lines)} lines) ──", file=sys.stderr)
            for line in lines:
                print(f"  {label[:4]}| {line}", file=sys.stderr)


def _crashed_child(procs: Sequence[tuple[str, Optional[subprocess.Popen]]]) -> Optional[str]:
    """Return a description of the first child that has exited, if any."""
    for label, proc in procs:
        if proc is not None and proc.poll() is not None:
            return f"{label} exited with code {proc.returncode}"
    return None


def _debug_flags_by_turn(base: str, session_id: str, timeout: float) -> Dict[int, Dict[str, Any]]:
    """Fetch per-turn parse flags from the dev debug endpoint, keyed by game turn.

    Best-effort: the debug drawer is a diagnostic, so a failure here must not
    turn a healthy smoke red.  That holds for the *shape* of the answer as well
    as for the transport — an entry without a ``turn_number`` would otherwise
    raise a KeyError out of this helper, escape to ``run_smoke``'s catch-all and
    report an otherwise-green run as a harness bug (exit 5).  A payload we
    cannot key by turn is the same situation as no payload at all: the fallback
    check does not run, and ``evaluate_turns`` warns that it did not.
    """
    try:
        debug = _request_json(f"{base}/sessions/{session_id}/debug", timeout=timeout)
    except SmokeFailure as exc:
        print(f"[smoke] Could not read debug flags ({exc}); continuing.")
        return {}
    turns = debug.get("turns")
    if not isinstance(turns, list):
        print(f"[smoke] Debug endpoint returned no turns list ({turns!r}); continuing.")
        return {}
    flags: Dict[int, Dict[str, Any]] = {}
    for entry in turns:
        if isinstance(entry, dict) and isinstance(entry.get("turn_number"), int):
            flags[entry["turn_number"]] = entry
        else:
            print(f"[smoke] Ignoring unkeyable debug turn entry: {entry!r}")
    return flags


def run_smoke(
    model_id: str,
    ci_hardware_factor: float,
    report_path: Optional[Path],
    *,
    model_sha256: Optional[str] = None,
    models_dir: Path = MODELS_DIR,
    wall_clock_budget_s: float = DEFAULT_WALL_CLOCK_BUDGET_S,
) -> int:
    """Run the full scripted smoke.  Returns the process exit code."""
    clock = Deadline(wall_clock_budget_s)
    # A call must be allowed to run past the latency we are about to judge it
    # on, or whoever gives up first decides the verdict instead of us: the
    # adapter's own timeout surfaces as HTTP 500 (class `runtime`, "the server
    # crashed") and our POST timeout surfaces as a transport error (also
    # `runtime`), when the truth is a slow model — class `budget`.
    #
    # The debrief, not a turn, is the slowest single generation (one long
    # structured document against one NPC reply), so the adapter ceiling is
    # sized for it: DEBRIEF_SLOWDOWN_FACTOR × the full-response CI ceiling.
    # Our own POST timeout then sits above the adapter's, so when something
    # really does hang it is the adapter that reports it, with a message that
    # names the knob.  The run's wall-clock deadline — not these timeouts — is
    # what bounds the job.
    full_ceiling_s = (
        BUDGETS_MS["full_response_ms"] * ci_hardware_factor * REGRESSION_TOLERANCE
    ) / 1000
    llama_timeout_s = max(300.0, full_ceiling_s * DEBRIEF_SLOWDOWN_FACTOR + 60.0)
    request_timeout_s = llama_timeout_s + 30.0

    results: Dict[str, Any] = {
        "model_id": model_id,
        "scenario_id": SCENARIO_ID,
        "ci_hardware_factor": ci_hardware_factor,
        "budgets_ms": dict(BUDGETS_MS),
        "ci_budgets_ms": {k: v * ci_hardware_factor for k, v in BUDGETS_MS.items()},
        "regression_tolerance": REGRESSION_TOLERANCE,
        "wall_clock_budget_s": wall_clock_budget_s,
        "measured_ms": {},
        "turns": [],
        "debrief": None,
        "verdict": "pending",
        "failure_class": None,
        "exit_code": None,
        "failures": [],
        "warnings": [],
    }

    model_path = models_dir / f"{model_id}.gguf"
    llama_proc: Optional[subprocess.Popen] = None
    core_proc: Optional[subprocess.Popen] = None
    llama_stderr_tail = StderrTail()
    core_stderr_tail = StderrTail()

    # convsim-core's throwaway data directory (SQLite db, WAL, logs).  Created
    # and removed by hand rather than with a `with TemporaryDirectory(...)`
    # inside the try: that block exits *before* the finally below, so the
    # directory would be deleted while convsim-core is still writing to it, and
    # an rmtree that lost that race would surface as an unexpected-error
    # `pipeline` verdict on an otherwise green run.  The finally stops both
    # children first, then removes the tree with errors ignored — cleanup must
    # never overturn a verdict.
    data_dir = Path(tempfile.mkdtemp(prefix="convsim-smoke-"))
    try:
        # ── checksum ──────────────────────────────────────────────────────────
        clock.enter("checksum")
        if model_sha256:
            print(f"[smoke] Verifying model checksum before use: {model_path}")
            verify_model_checksum(model_path, model_sha256)
        elif not model_path.exists():
            raise SmokeFailure(
                FailureClass.DOWNLOAD,
                f"Model file not found: {model_path}. Run with --download-only first, "
                "or check that the model cache is populated.",
            )
        else:
            results["warnings"].append(
                "No --model-sha256 given: checksum drift was not checked before the run"
            )

        # ── runtime ───────────────────────────────────────────────────────────
        clock.enter("runtime_start")
        # Both ports before anything is spawned: the smoke has to serve itself,
        # or its proof that a real pinned model drove the conversation is worth
        # nothing.
        _assert_port_free(LLAMA_SERVER_PORT, "llama-server")
        _assert_port_free(CORE_PORT, "convsim-core")
        print(f"\n[smoke] Starting llama-server on port {LLAMA_SERVER_PORT} "
              f"with model: {model_path.name}")
        llama_proc = _start_llama_server(model_path, LLAMA_SERVER_PORT)
        threading.Thread(target=_drain, args=(llama_proc.stderr, llama_stderr_tail), daemon=True).start()
        threading.Thread(target=_drain, args=(llama_proc.stdout,), daemon=True).start()

        print("[smoke] Waiting for llama-server (model load)…")
        _wait_for_http(
            f"http://127.0.0.1:{LLAMA_SERVER_PORT}/v1/models",
            timeout_s=clock.cap(300.0),
            label="llama-server",
            proc=llama_proc,
        )
        print("[smoke] llama-server ready.")

        print(f"[smoke] Starting convsim-core on port {CORE_PORT}…")
        core_proc = _start_core(data_dir, CORE_PORT, LLAMA_SERVER_PORT, llama_timeout_s)
        threading.Thread(target=_drain, args=(core_proc.stderr, core_stderr_tail), daemon=True).start()
        threading.Thread(target=_drain, args=(core_proc.stdout,), daemon=True).start()

        base = f"http://127.0.0.1:{CORE_PORT}/api"
        _wait_for_http(
            f"{base}/health",
            timeout_s=clock.cap(120.0),
            label="convsim-core",
            proc=core_proc,
        )

        # Sanity-check that the real runtime is wired (not the fake default).
        health = _request_json(f"{base}/health", timeout=clock.cap(30.0))
        # `or {}`, not a `{}` default: an absent llm_runtime already falls
        # through to the clean "core reports None" verdict below, but an explicit
        # JSON null would make .get() raise AttributeError and report a changed
        # /health contract as a bug in this harness.  Same reason as _excerpt_any.
        runtime_id = (health.get("llm_runtime") or {}).get("runtime_id")
        results["runtime_id"] = runtime_id
        print(f"[smoke] convsim-core ready (runtime_id={runtime_id}).")
        if runtime_id != "llama_cpp":
            raise SmokeFailure(
                FailureClass.PIPELINE,
                f"Expected runtime_id 'llama_cpp' but core reports {runtime_id!r}. "
                "Check CONVSIM_RUNTIME_ID wiring — the smoke must not run on a fake runtime.",
            )

        # ── conversation ──────────────────────────────────────────────────────
        clock.enter("conversation")
        session = _request_json(f"{base}/sessions", payload={
            "scenario_id": SCENARIO_ID,
            "difficulty": "standard",
            "player_role_name": "Smoke Tester",
            "language": "en",
            "input_mode": "text-only",
            "tts_enabled": False,
            "show_state_meters": False,
            "save_transcript": False,  # no transcript file written during smoke runs
            "seed": 42,
        }, timeout=clock.cap(30.0))
        session_id = session["session_id"]
        results["session_id"] = session_id
        print(f"[smoke] Session {session_id} created. Starting session…")

        # /start replays the scenario's authored opening line — no model
        # call — so it is measured for the documented session-start metric but
        # needs no inference-sized timeout.
        t0 = time.monotonic()
        start = _request_json(
            f"{base}/sessions/{session_id}/start",
            payload={},
            timeout=clock.cap(60.0),
        )
        session_start_ms = (time.monotonic() - t0) * 1000
        opening = _npc_turn_content(start.get("events", []))
        print(f"[smoke] NPC opening (authored) in {session_start_ms:.0f} ms: "
              f"{_excerpt(opening)!r}")
        results["measured_ms"]["session_start_ms"] = round(session_start_ms)
        results["turns"].append({
            "label": "npc_opening",
            "turn_number": 0,
            "model_generated": False,
            "latency_ms": round(session_start_ms),
            "npc_excerpt": _excerpt(opening),
        })

        turn_latencies: List[float] = []
        ended_by_scenario = False
        for i, player_text in enumerate(SCRIPTED_PLAYER_TURNS, start=1):
            clock.check()
            print(f"[smoke] Player turn {i}/{len(SCRIPTED_PLAYER_TURNS)}…")
            t0 = time.monotonic()
            turn = _request_json(
                f"{base}/sessions/{session_id}/turn",
                payload={"content": player_text},
                timeout=clock.cap(request_timeout_s),
            )
            latency_ms = (time.monotonic() - t0) * 1000
            turn_latencies.append(latency_ms)
            npc_text = _npc_turn_content(turn.get("events", []))
            replayed_opening = _replays_opening(npc_text, opening)
            print(f"  {latency_ms:.0f} ms | NPC: {_excerpt(npc_text)!r}"
                  + (" [replays the authored opening]" if replayed_opening else ""))
            results["turns"].append({
                "label": f"player_turn_{i}",
                "turn_number": i,
                "model_generated": True,
                "latency_ms": round(latency_ms),
                "npc_excerpt": _excerpt(npc_text),
                # Real model output that is not a reply — see _replays_opening.
                # The parse flags below cannot tell this from a healthy turn.
                "replayed_opening": replayed_opening,
                "ending_type": turn.get("ending_type"),
                # What the model volunteered for the debrief to score.  Recorded
                # per turn so an unscored debrief can be attributed without
                # re-running anything — see evaluate_debrief.
                "rubric_observation_count": _rubric_observation_count(
                    turn.get("events", [])
                ),
            })
            if turn.get("ending_type"):
                # The turn pipeline already moved the session to 'Ended', so
                # POST /end would 409 — see end_session() in the sessions
                # router.  Record that and skip the explicit end below.
                ended_by_scenario = True
                print(f"[smoke] Scenario ended early (ending_type={turn['ending_type']}); "
                      "stopping the scripted turns.")
                break

        results["scripted_turns_played"] = len(turn_latencies)
        if len(turn_latencies) < len(SCRIPTED_PLAYER_TURNS):
            # Not a failure: the model is allowed to close the conversation
            # (session_control.continue_session), and the product handled it.
            # But the job exists to play a *multi-turn* conversation, and a run
            # that played one turn proves less than one that played three — say
            # so in the summary rather than let a short green run read like a
            # full one.
            results["warnings"].append(
                f"Only {len(turn_latencies)} of {len(SCRIPTED_PLAYER_TURNS)} scripted "
                f"player turns ran: the NPC ended the session early (ending_type="
                f"{results['turns'][-1].get('ending_type')!r}), so this run proves "
                "less about multi-turn behaviour than a full playthrough"
            )

        # The median is the headline full-response figure: a single unlucky
        # turn (runner steal, a long NPC answer) must not flap the nightly,
        # while a real regression moves every turn and so moves the median.
        results["measured_ms"]["full_response_ms"] = round(statistics.median(turn_latencies))
        results["measured_ms"]["full_response_max_ms"] = round(max(turn_latencies))

        # Per-turn parse flags tell us whether the model's structured output
        # was accepted or quietly replaced by the safe fallback.
        flags = _debug_flags_by_turn(base, session_id, clock.cap(30.0))
        for turn in results["turns"]:
            flag = flags.get(turn["turn_number"])
            if flag:
                turn["used_fallback"] = bool(flag.get("used_fallback"))
                turn["used_native_structured_output"] = bool(
                    flag.get("used_native_structured_output")
                )

        # ── debrief ───────────────────────────────────────────────────────────
        clock.enter("debrief")
        if ended_by_scenario:
            print("[smoke] Session already Ended by the scenario; skipping /end.")
        else:
            print("[smoke] Ending session…")
            _request_json(
                f"{base}/sessions/{session_id}/end", payload={}, timeout=clock.cap(30.0)
            )
        print("[smoke] Generating debrief (real model call)…")
        t0 = time.monotonic()
        debrief = _request_json(
            f"{base}/sessions/{session_id}/debrief",
            payload={},
            timeout=clock.cap(request_timeout_s),
        )
        debrief_ms = (time.monotonic() - t0) * 1000
        results["measured_ms"]["debrief_ms"] = round(debrief_ms)
        results["debrief"] = {
            "outcome": debrief.get("outcome"),
            "total_turns": debrief.get("total_turns"),
            "scores": debrief.get("scores"),
            "overall_score": debrief.get("overall_score"),
            # _excerpt_any, not _excerpt: this report is assembled *before*
            # evaluate_debrief runs, so a summary that is not text would raise
            # here and the classified verdict evaluate_debrief was about to
            # reach would never be assembled.  See _excerpt_any.
            "summary_excerpt": _excerpt_any(debrief.get("summary")),
            "strength_count": len(debrief.get("strengths") or []),
            "improvement_count": len(debrief.get("improvements") or []),
            "turning_point_count": len(debrief.get("turning_points") or []),
            "used_fallback": bool(debrief.get("used_fallback")),
            "latency_ms": round(debrief_ms),
        }
        # Everything the NPC turns offered the debrief to score.  An unscored
        # debrief means something different depending on whether this is zero —
        # and something different again when we could not read it, so an
        # unreadable turn payload yields None rather than a confident zero.
        # A positive total is still conclusive even with an unreadable turn
        # among the others: observations *were* seen, so the debrief losing
        # them is the cause whatever the missing turn carried.
        observations_seen = _total_rubric_observations(results["turns"])
        results["rubric_observations_seen"] = observations_seen
        print(f"[smoke] Debrief in {debrief_ms:.0f} ms | "
              f"overall_score={debrief.get('overall_score')} "
              f"scores={debrief.get('scores')} "
              f"rubric_observations_from_turns="
              f"{'unknown' if observations_seen is None else observations_seen}")

        # ── assertions ────────────────────────────────────────────────────────
        clock.enter("assertions")
        turn_failures, turn_warnings = evaluate_turns(results["turns"])
        debrief_failures, debrief_warnings = evaluate_debrief(
            debrief,
            rubric_observations_seen=observations_seen,
            # A conversation that fell back on every generated turn reaches the
            # debrief with nothing to score for a reason that has nothing to do
            # with rubric prompting — see UNSCORED_AFTER_FALLBACK_NOTE.
            turns_all_fell_back=_all_generated_turns_fell_back(results["turns"]),
        )
        results["warnings"] += turn_warnings + debrief_warnings
        pipeline_failures = turn_failures + debrief_failures
        if pipeline_failures:
            results["failures"] = pipeline_failures
            raise SmokeFailure(
                FailureClass.PIPELINE,
                f"{len(pipeline_failures)} end-to-end assertion(s) failed",
            )

        # ── budget ────────────────────────────────────────────────────────────
        clock.enter("budget")
        budget_failures, budget_lines = evaluate_budgets(
            results["measured_ms"], ci_hardware_factor
        )
        for line in budget_lines:
            print(f"  {line}")
        if budget_failures:
            results["failures"] = budget_failures
            raise SmokeFailure(
                FailureClass.BUDGET, f"{len(budget_failures)} latency budget(s) exceeded"
            )

        results["verdict"] = "pass"
        results["exit_code"] = 0

    except SmokeFailure as exc:
        # Precedence, strongest evidence first:
        #   1. A crashed child outranks whatever the client saw — "core exited
        #      with code 1" is the real story, not the connection reset it caused.
        #   2. An exhausted wall clock outranks the transport error it produced:
        #      cap() shrinks each request timeout to the budget that is left, so
        #      the last request before the deadline dies client-side and reports
        #      itself as RUNTIME ("the server never answered"). The honest
        #      verdict is TIMEOUT, which is the class whose remedy says to look
        #      at phase_durations_s.
        crashed = _crashed_child((("llama-server", llama_proc), ("convsim-core", core_proc)))
        out_of_time = not crashed and clock.remaining_s <= 0
        if crashed:
            failure_class = FailureClass.RUNTIME
        elif out_of_time:
            failure_class = FailureClass.TIMEOUT
        else:
            failure_class = exc.failure_class
        results["verdict"] = "fail"
        results["failure_class"] = failure_class
        results["exit_code"] = EXIT_CODES[failure_class]
        results["failed_phase"] = exc.phase or clock.phase
        # Record the remedy in the artifact too: the failure table in
        # docs/real-model-smoke.md sends triage to the JSON report for several
        # classes, and a report that names a class without the advice attached
        # makes the reader go and look the mapping up again.  The failure's own
        # remedy only survives while its class does — once a crashed child or an
        # exhausted clock has overruled the class, its advice describes a
        # different failure than the one being reported.
        results["remedy"] = (
            exc.remedy if failure_class == exc.failure_class else REMEDIES[failure_class]
        )
        if not results["failures"]:
            results["failures"] = [str(exc)]
        if crashed:
            results["failures"].insert(0, crashed)
        elif out_of_time and exc.failure_class != FailureClass.TIMEOUT:
            results["failures"].insert(
                0,
                f"Wall-clock budget of {wall_clock_budget_s:.0f} s exhausted during phase "
                f"{results['failed_phase']!r} (elapsed {clock.elapsed_s:.0f} s)",
            )
        if failure_class == FailureClass.TIMEOUT:
            # TIMEOUT is reached before the budget phase can run for exactly the
            # regression `budget` is meant to catch, so attach the measurement
            # that tells the two apart.  See timeout_latency_evidence.
            evidence = timeout_latency_evidence(results["turns"], full_ceiling_s * 1000)
            if evidence:
                results["failures"].append(evidence)
        _dump_stderr_tails((("convsim-core", core_stderr_tail), ("llama-server", llama_stderr_tail)))
        _print_banner(failure_class, results["failures"], remedy=results["remedy"])

    # Exception, not BaseException: a Ctrl-C should still stop the children (the
    # finally block below) but must not be dressed up as a product failure.
    except Exception as exc:
        results["verdict"] = "fail"
        results["failure_class"] = FailureClass.PIPELINE
        results["exit_code"] = EXIT_CODES[FailureClass.PIPELINE]
        results["failed_phase"] = clock.phase
        results["failures"] = [
            f"Unexpected error in phase {clock.phase!r}: {exc!r} — this is most likely "
            "a bug in the smoke harness itself, not in the product "
            "(tests/scripts/test_nightly_model_smoke.py covers its logic)"
        ]
        # Borrowing `pipeline`'s exit code, not its cause: the class remedy
        # ("inspect the per-turn used_fallback flags") would point triage at
        # model output when the traceback above is the thing to read.
        results["remedy"] = (
            "Read the traceback above and the phase it names. This is a harness "
            "bug, not a product verdict — add a case to "
            "tests/scripts/test_nightly_model_smoke.py once you have it."
        )
        _dump_stderr_tails((("convsim-core", core_stderr_tail), ("llama-server", llama_stderr_tail)))
        _print_banner(FailureClass.PIPELINE, results["failures"], remedy=results["remedy"])

    finally:
        for proc in (core_proc, llama_proc):
            if proc is None:
                continue
            proc.terminate()
            try:
                proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                proc.kill()
        # Only now that convsim-core is stopped is its data directory safe to
        # remove.  errors ignored: a stray file left behind is a tidiness
        # problem, not a reason to turn a decided verdict into a traceback.
        shutil.rmtree(data_dir, ignore_errors=True)
        results["phase_durations_s"] = clock.finish()
        results["wall_clock_s"] = round(clock.elapsed_s, 1)

    if results["verdict"] == "pass":
        generated = sum(1 for t in results["turns"] if t.get("model_generated"))
        print(f"\n[smoke] PASSED — real model {model_id} produced "
              f"{generated} NPC turn(s) and a scored debrief "
              f"(overall_score={(results['debrief'] or {}).get('overall_score')}) "
              f"in {results['wall_clock_s']:.0f} s.")
        for warning in results["warnings"]:
            print(f"  ! {warning}")

    _write_report(report_path, results)
    _write_step_summary(results)
    return int(results["exit_code"] or 0)


# ── CLI ───────────────────────────────────────────────────────────────────────


class _ClassifiedArgumentParser(argparse.ArgumentParser):
    """An ``ArgumentParser`` whose usage errors land in a known failure class.

    argparse exits 2 on a bad command line, and EXIT_CODES reads 2 as
    ``download`` — whose remedy is "nothing about the app changed, re-run the
    job". That would send a triager round a loop re-running a job that cannot
    succeed. A malformed invocation is a harness problem, which is exactly what
    ``pipeline`` means for everything else the harness did not anticipate.
    """

    def error(self, message: str) -> NoReturn:
        self.print_usage(sys.stderr)
        _print_banner(
            FailureClass.PIPELINE,
            [f"Invalid command line: {message}"],
            remedy="Fix the invocation. See the usage above, the examples in this "
                   "file's docstring, or the smoke step in "
                   ".github/workflows/model-smoke-nightly.yml.",
        )
        sys.exit(EXIT_CODES[FailureClass.PIPELINE])


def _use_line_buffered_output() -> None:
    """Make stdout arrive in step with stderr, line by line.

    CI captures this script's stdout through a pipe, so Python block-buffers it
    (8 KB) while stderr stays unbuffered.  Two things break as a result, and
    both are the log a triager actually reads:

    * nothing streams.  A run spends ~11 min inside the conversation and
      debrief phases, and the "Player turn 2/3…" lines that say where it got to
      only reach the log when the buffer fills or the process exits.
    * the failure banner arrives *before* the context it explains.  The banner
      and the child stderr tails go to stderr; the phase progress, per-turn
      latencies and budget arithmetic go to stdout, so the merged log shows the
      verdict first and the evidence afterwards.
    """
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(line_buffering=True)  # type: ignore[union-attr]
        except (AttributeError, ValueError):
            # Not a TextIOWrapper (pytest's capture, a redirect_stdout buffer).
            # Buffering is then the caller's concern, not ours.
            pass


def main(argv: Optional[Sequence[str]] = None) -> int:
    _use_line_buffered_output()
    parser = _ClassifiedArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--print-registry-model", metavar="ROLE", default=None,
                        help="Resolve the registry model with this role (e.g. 'starter'), "
                             "write id/url/sha256 to $GITHUB_OUTPUT, and exit.")
    parser.add_argument("--download-only", action="store_true",
                        help="Download and verify the model file, then exit.")
    parser.add_argument("--verify-only", action="store_true",
                        help="Verify the on-disk model against --model-sha256, then exit. "
                             "A mismatch deletes the file, so a re-run re-downloads it "
                             "instead of re-verifying the same bad bytes.")
    parser.add_argument("--model-url", default=None,
                        help="Download URL (required for --download-only).")
    parser.add_argument("--model-sha256", default=None,
                        help="Expected SHA-256 hex. Required for --download-only/--verify-only; "
                             "on a full run the model is re-verified before use when given.")
    parser.add_argument("--model-id", default=None,
                        help="Registry model ID (e.g. qwen3-4b-instruct-q4_k_m).")
    parser.add_argument("--models-dir", default=None,
                        help=f"Directory holding <model-id>.gguf (default {MODELS_DIR}).")
    parser.add_argument("--ci-hardware-factor", type=float, default=1.0,
                        help="Multiplier applied to documented budgets for CI hardware (default 1.0).")
    parser.add_argument("--wall-clock-budget-s", type=float, default=DEFAULT_WALL_CLOCK_BUDGET_S,
                        help=f"Fail with exit {EXIT_CODES[FailureClass.TIMEOUT]} if the run "
                             f"exceeds this many seconds (default {DEFAULT_WALL_CLOCK_BUDGET_S:.0f}).")
    parser.add_argument("--report-path", default=None, help="Write JSON report to this path.")

    args = parser.parse_args(argv)
    models_dir = Path(args.models_dir) if args.models_dir else MODELS_DIR

    try:
        if args.print_registry_model:
            model = resolve_registry_model(args.print_registry_model)
            _emit_github_output({
                "model_id": model["id"],
                "model_url": model["url"],
                "model_sha256": model["sha256"],
                "model_size_gb": model["size_gb"],
            })
            return 0

        if not args.model_id:
            parser.error("--model-id is required")

        if args.download_only:
            if not args.model_url or not args.model_sha256:
                parser.error("--model-url and --model-sha256 are required with --download-only")
            print(f"[smoke] Downloading model {args.model_id}…")
            download_model(args.model_url, args.model_sha256, args.model_id, models_dir)
            return 0

        if args.verify_only:
            if not args.model_sha256:
                parser.error("--model-sha256 is required with --verify-only")
            print(f"[smoke] Verifying cached model {args.model_id}…")
            verify_model_checksum(models_dir / f"{args.model_id}.gguf", args.model_sha256)
            return 0

        # Inside the handler, not after it: run_smoke classifies everything in
        # its own try/finally, but its prologue (the throwaway data directory)
        # and its epilogue (the report and step-summary writes that follow the
        # verdict) sit outside that block.  An OSError there — a full disk is
        # the realistic one, right after a 2.5 GB download and a 2.5 GB cache
        # save — would escape as a bare traceback and exit 1.
        return run_smoke(
            args.model_id,
            args.ci_hardware_factor,
            Path(args.report_path) if args.report_path else None,
            model_sha256=args.model_sha256,
            models_dir=models_dir,
            wall_clock_budget_s=args.wall_clock_budget_s,
        )

    except SmokeFailure as exc:
        _print_banner(exc.failure_class, [str(exc)], remedy=exc.remedy)
        _write_step_summary({
            "verdict": "fail",
            "model_id": args.model_id,
            "failure_class": exc.failure_class,
            "exit_code": exc.exit_code,
            "failures": [str(exc)],
            "remedy": exc.remedy,
        })
        return exc.exit_code

    # Nothing may leave main() unclassified.  The pre-run modes (registry
    # lookup, download, verify) have no run_smoke around them to catch what
    # they did not anticipate — an unparseable registry.yaml, a missing file, a
    # bad --models-dir — and run_smoke itself has a prologue and an epilogue
    # outside its own handlers.  Letting any of that escape exits 1, which
    # EXIT_CODES reads as `budget`: the one class that says "the product is
    # fine, it is just slow".  Classify them the way run_smoke classifies its
    # own surprises instead, so a banner and a step summary are still written
    # and exit 1 keeps meaning only what it claims to mean.
    except Exception as exc:  # noqa: BLE001 — anything unanticipated, reported not raised
        failures = [
            f"Unexpected error outside the smoke's own classification: {exc!r} — "
            "this is most likely a bug in the smoke harness, a malformed "
            "model-registry/registry.yaml or an unusable disk, not a product failure"
        ]
        remedy = (
            "This escaped run_smoke's own error handling, so it says nothing about "
            "the product. Re-run the harness locally with the same arguments "
            "(docs/real-model-smoke.md) and fix the registry file, the environment, "
            "or the harness bug in the traceback above."
        )
        _print_banner(FailureClass.PIPELINE, failures, remedy=remedy)
        _write_step_summary({
            "verdict": "fail",
            "model_id": args.model_id,
            "failure_class": FailureClass.PIPELINE,
            "exit_code": EXIT_CODES[FailureClass.PIPELINE],
            "failures": failures,
            "remedy": remedy,
        })
        return EXIT_CODES[FailureClass.PIPELINE]


if __name__ == "__main__":
    sys.exit(main())
