def render_step_summary(results: Dict[str, Any]) -> str:
    """Render the GitHub step summary: verdict, class, timings, what to do next."""
    verdict = results.get("verdict", "unknown")
    icon = {"pass": "✅", "fail": "❌"}.get(verdict, "⚠️")
    lines = [
        f"## {icon} Real-model smoke: {verdict.upper()}",
        "",
    ]
    # Same reasoning as the wall clock below: `--print-registry-model` runs
    # before any --model-id exists, and it is the mode that fails when the
    # registry names no usable `starter` entry or has not pinned one yet. Its
    # summary led with "**Model:** `None`" — a field the run never resolved,
    # presented as the model it ran on, directly above the verdict.
    if results.get("model_id"):
        lines.append(f"- **Model:** `{results['model_id']}`")
    # Only the smoke run keeps a clock.  The pre-run modes (registry lookup,
    # download, verify) write a summary too, and defaulting their missing
    # timings to zero printed "Wall clock: 0 s (budget 0 s)" at the top of a
    # download or checksum verdict — a measurement the run never took, in the
    # first thing a triager reads.
    if results.get("wall_clock_s") is not None:
        lines.append(
            f"- **Wall clock:** {results['wall_clock_s']:.0f} s "
            f"(budget {results.get('wall_clock_budget_s', 0):.0f} s)"
        )
    if verdict == "fail":
        cls = results.get("failure_class", "unknown")
        lines += [
            f"- **Failure class:** `{cls}` (exit {results.get('exit_code')})",
            "",
            "### Failures",
            *[f"- {f}" for f in results.get("failures", [])],
            "",
            "### What to do",
            results.get("remedy") or REMEDIES.get(cls, "No remedy recorded."),
        ]
    measured = results.get("measured_ms") or {}
    if measured:
        lines += ["", "### Measured latency", "", "| Metric | Measured | CI ceiling |", "|---|---|---|"]
        factor = results.get("ci_hardware_factor", 1.0)
        for key, value in measured.items():
            budget = BUDGETS_MS.get(key)
            ceiling = (
                f"{budget * factor * REGRESSION_TOLERANCE:.0f} ms" if budget else "—"
            )
            lines.append(f"| `{key}` | {value:.0f} ms | {ceiling} |")
    phases = results.get("phase_durations_s") or {}
    if phases:
        lines += ["", "### Phase durations", "", "| Phase | Seconds |", "|---|---|"]
        lines += [f"| `{k}` | {v:.0f} |" for k, v in phases.items()]
    if results.get("warnings"):
        lines += ["", "### Warnings", *[f"- {w}" for w in results["warnings"]]]
    return "\n".join(lines) + "\n"


def _write_step_summary(results: Dict[str, Any]) -> None:
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if not path:
        return
    try:
        with open(path, "a", encoding="utf-8") as f:
            f.write(render_step_summary(results))
    except OSError as exc:  # never let reporting break the verdict
        print(f"[smoke] Could not write step summary: {exc}", file=sys.stderr)


def _print_banner(
    failure_class: str, failures: Sequence[str], *, remedy: Optional[str] = None
) -> None:
    """Print the failure banner.  ``remedy`` overrides the class default.

    Some failures borrow a class's exit code without matching its usual cause —
    a harness bug reported as ``pipeline``, say — and printing "inspect the
    per-turn used_fallback flags" under those sends triage the wrong way.
    """
    bar = "━" * 72
    print(f"\n{bar}", file=sys.stderr)
    print(f"[smoke] FAILED — class: {failure_class.upper()} "
          f"(exit {EXIT_CODES[failure_class]})", file=sys.stderr)
    print(bar, file=sys.stderr)
    for f in failures:
        print(f"  ✗ {f}", file=sys.stderr)
    print(f"\n  → {remedy or REMEDIES[failure_class]}", file=sys.stderr)
    print(f"{bar}\n", file=sys.stderr)


def _write_report(report_path: Optional[Path], results: Dict[str, Any]) -> None:
    if not report_path:
        return
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(f"[smoke] Report written to {report_path}")


