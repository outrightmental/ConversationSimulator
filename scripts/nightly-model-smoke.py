class SmokeFailure(Exception):
    """A failure with a known class, so CI can distinguish *why* the smoke failed.

    ``remedy`` overrides the class default for the failures that borrow a
    class's exit code without matching its usual cause.  Printing the class
    remedy under those sends triage the wrong way — the whole point of the
    classification is that the advice next to the banner is actionable.
    """

    def __init__(
        self,
        failure_class: str,
        message: str,
        *,
        phase: Optional[str] = None,
        remedy: Optional[str] = None,
    ) -> None:
        super().__init__(message)
        self.failure_class = failure_class
        self.phase = phase
        self._remedy = remedy

    @property
    def exit_code(self) -> int:
        return EXIT_CODES[self.failure_class]

    @property
    def remedy(self) -> str:
        return self._remedy or REMEDIES[self.failure_class]


# ── Wall-clock budget ─────────────────────────────────────────────────────────


class Deadline:
    """Tracks the run's wall-clock budget and which phase is consuming it."""

    def __init__(self, budget_s: float) -> None:
        self.budget_s = budget_s
        self._start = time.monotonic()
        self._phase = "startup"
        self._phase_start = self._start
        self.phase_durations_s: Dict[str, float] = {}

    @property
    def elapsed_s(self) -> float:
        return time.monotonic() - self._start

    @property
    def remaining_s(self) -> float:
        return self.budget_s - self.elapsed_s

    @property
    def phase(self) -> str:
        return self._phase

    def enter(self, phase: str) -> None:
        """Check the budget, then close out this phase's duration and start ``phase``.

        The check comes first, while ``self._phase`` is still the phase that has
        been running: it is the one that consumed the budget, and so the one a
        triager needs named.  Switching phases first would attribute the overrun
        to a phase that has not executed a single instruction — reporting
        "exhausted during phase 'debrief'" for a conversation that ran long.
        """
        self.check()
        self._close_phase(phase)

    def finish(self) -> Dict[str, float]:
        """Close the books without checking the budget.

        Called from ``run_smoke``'s ``finally``, where an exhausted budget has
        already been classified: raising here would escape the handler and throw
        the verdict away, turning a reportable timeout into a bare traceback.
        """
        self._close_phase("done")
        return self.phase_durations_s

    def _close_phase(self, next_phase: str) -> None:
        now = time.monotonic()
        self.phase_durations_s[self._phase] = round(
            self.phase_durations_s.get(self._phase, 0.0) + (now - self._phase_start), 1
        )
        self._phase = next_phase
        self._phase_start = now

    def check(self) -> None:
        if self.remaining_s <= 0:
            raise SmokeFailure(
                FailureClass.TIMEOUT,
                f"Wall-clock budget of {self.budget_s:.0f} s exhausted during phase "
                f"{self._phase!r} (elapsed {self.elapsed_s:.0f} s)",
                phase=self._phase,
            )

    def cap(self, timeout_s: float) -> float:
        """Clamp a request timeout to what is left of the budget."""
        self.check()
        return max(5.0, min(timeout_s, self.remaining_s))


# ── Registry ──────────────────────────────────────────────────────────────────


# A registry that does not describe a usable model is a repository problem, not
# a network one.  It borrows `pipeline`'s exit code — the class this harness
# uses for everything it could not carry out — rather than `download`, whose
# remedy ends "Nothing about the app changed — re-run the job": no number of
# re-runs makes a missing `role: starter` entry appear, and the checksum the
# cache key is built from never existed to drift.
REGISTRY_REMEDY = (
    "model-registry/registry.yaml does not describe a usable model for the "
    "requested role, so the job never got as far as fetching anything. "
    "Re-running cannot fix it: repair the registry entry (validate with "
    "scripts/validate-registry.py) and merge."
)

# The placeholder the registry schema allows in `download.url` and
# `download.sha256` for an entry that has been added but not yet pinned
# (model-registry.schema.json documents both: "or 'PENDING' for pre-release
# entries").  `scripts/validate-registry.py` fails on it — but only in
# registry-nightly.yml, which does not run per-PR, so a `role: starter` entry
# can reach main un-pinned.
#
# It has to be rejected here rather than passed along as a value, because both
# fields carry it into a verdict that blames the wrong thing:
#
#   * sha256 "PENDING" makes the cache key `…-PENDING`, downloads 2.5 GB, and
#     then fails `checksum` (exit 3) — whose remedy says the pinned upstream
#     file was replaced and "do NOT relax this check" — while deleting the
#     file it just fetched;
#   * url "PENDING" raises out of urllib's Request constructor, which sits
#     outside _download_with_progress's handler, so it lands in main's
#     catch-all as "most likely a bug in the smoke harness" (exit 5).
#
# An un-pinned entry is neither. It is precisely the "registry does not
# describe a usable model" case REGISTRY_REMEDY exists for, and catching it at
# the one lookup means the `--print-registry-model` step fails first, before
# any cache key is built or any byte is fetched.
REGISTRY_PENDING = "PENDING"


def resolve_registry_model(role: str, registry_path: Path = REGISTRY_PATH) -> Dict[str, Any]:
    """Return ``{id, url, sha256, size_gb}`` for the registry model with ``role``.

    Single source of truth for the workflow: the cache key, the download and the
    checksum verification all come from this one lookup, so they cannot drift
    apart. ``yaml`` is imported lazily so the module imports without PyYAML.
    """
    import yaml  # lazy: keeps this module importable for unit tests without PyYAML

    registry = yaml.safe_load(registry_path.read_text(encoding="utf-8"))
    matches = [m for m in registry.get("models", []) if m.get("role") == role]
    if not matches:
        raise SmokeFailure(
            FailureClass.PIPELINE,
            f"No model with role {role!r} in {registry_path}",
            remedy=REGISTRY_REMEDY,
        )
    if len(matches) > 1:
        raise SmokeFailure(
            FailureClass.PIPELINE,
            f"Registry has {len(matches)} models with role {role!r}; expected exactly one",
            remedy=REGISTRY_REMEDY,
        )
    model = matches[0]
    download = model.get("download", {})
    sha256 = download.get("sha256")
    url = download.get("url")
    if not sha256 or not url:
        raise SmokeFailure(
            FailureClass.PIPELINE,
            f"Registry model {model.get('id')!r} is missing download.url or download.sha256",
            remedy=REGISTRY_REMEDY,
        )
    unpinned = [
        field
        for field, value in (("url", url), ("sha256", sha256))
        if value == REGISTRY_PENDING
    ]
    if unpinned:
        raise SmokeFailure(
            FailureClass.PIPELINE,
            f"Registry model {model.get('id')!r} is not pinned yet: "
            f"{', '.join('download.' + f for f in unpinned)} "
            f"still reads {REGISTRY_PENDING!r}. There is nothing to download or "
            "verify against, so the smoke cannot run on this model.",
            remedy=REGISTRY_REMEDY,
        )
    return {
        "id": model["id"],
        "url": url,
        "sha256": sha256,
        "size_gb": model.get("size_gb"),
    }


def _emit_github_output(values: Dict[str, Any]) -> None:
    """Write ``key=value`` lines to $GITHUB_OUTPUT (and always to stdout)."""
    lines = [f"{k}={v}" for k, v in values.items()]
    for line in lines:
        print(line)
    out = os.environ.get("GITHUB_OUTPUT")
    if out:
        with open(out, "a", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")


# ── Download and checksum ─────────────────────────────────────────────────────


def _download_with_progress(url: str, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    print(f"  Downloading {url[:80]}…")
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "convsim-smoke/1.0"})
    except ValueError as exc:
        # urllib raises out of the *constructor* for a string it cannot read as
        # a URL ("unknown url type"), i.e. before the handler below exists. That
        # escaped to main's catch-all and was reported as "most likely a bug in
        # the smoke harness", with a remedy telling the reader to re-run with
        # the same arguments — when the argument is the whole problem.
        #
        # Not `download` either: nothing was fetched and no re-run or registry
        # URL check changes the outcome. This is the harness being handed an
        # input it cannot act on, which is what `pipeline` covers for everything
        # else of that kind, with a remedy naming both places the string can
        # come from. The realistic source is the local repro in
        # docs/real-model-smoke.md, whose --model-url is a placeholder the
        # reader is meant to substitute.
        raise SmokeFailure(
            FailureClass.PIPELINE,
            f"Not a usable download URL: {url[:120]!r} ({exc})",
            remedy=(
                "Nothing was fetched — the string is not a URL urllib can "
                "request. If it came from --model-url on the command line, "
                "substitute the real URL printed by "
                "`--print-registry-model starter` (the repro block in "
                "docs/real-model-smoke.md shows a placeholder, not a value). "
                "If it came from the registry, repair download.url in "
                "model-registry/registry.yaml and validate with "
                "scripts/validate-registry.py --url-check."
            ),
        ) from exc
    try:
        with urllib.request.urlopen(req, timeout=600) as resp, open(dest, "wb") as f:
            total = int(resp.headers.get("Content-Length", 0)) or None
            downloaded = 0
            chunk = 1 << 20  # 1 MB
            last_logged_pct = -PROGRESS_LOG_STEP_PCT
            while True:
                buf = resp.read(chunk)
                if not buf:
                    break
                f.write(buf)
                downloaded += len(buf)
                if total:
                    pct = int(downloaded / total * 100)
                    if pct - last_logged_pct >= PROGRESS_LOG_STEP_PCT:
                        last_logged_pct = pct
                        print(
                            f"\r  {pct}% ({downloaded // 1_048_576} / {total // 1_048_576} MB)",
                            end="",
                            flush=True,
                        )
        print()
    except Exception as exc:  # noqa: BLE001 — see below
        # Network failure, HTTP error, or a full disk — all "could not fetch the
        # model", none of which say anything about the app under test.  Remove the
        # partial file so a re-run does not checksum-fail on a truncated download.
        #
        # Deliberately broader than OSError: a cut-off 2.5 GB response raises
        # http.client.IncompleteRead, which is NOT an OSError, so an OSError-only
        # handler let a truncated download escape as a bare traceback — exit 1,
        # which EXIT_CODES reads as `budget` — and left the partial file on disk
        # for the next run to checksum-fail on.
        dest.unlink(missing_ok=True)
        raise SmokeFailure(
            FailureClass.DOWNLOAD,
            f"Download failed for {url[:120]}: {exc!r}",
        ) from exc


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def verify_model_checksum(path: Path, expected: str, *, delete_on_mismatch: bool = True) -> str:
    """Hash ``path`` and compare to ``expected``; raise on drift.

    A mismatch deletes the file by default: leaving a known-bad GGUF in the CI
    cache would make every subsequent run fail on the same corrupt bytes, since
    the cache key is the expected hash and a cache hit skips the download.

    ``expected`` is compared as a hex *value*, not as a string: a digest that
    differs only in case or surrounding whitespace is the same digest, and
    string equality would call it drift.  That matters because of what a
    mismatch does — it deletes a 2.5 GB file and reports "the pinned upstream
    file was replaced … do NOT relax this check", which is an expensive and
    thoroughly misleading verdict to hand someone who pasted an upper-case
    hash into the local repro in docs/real-model-smoke.md.
    """
    if not path.exists():
        raise SmokeFailure(
            FailureClass.DOWNLOAD,
            f"Model file not found: {path}. The cache restore produced no model and no "
            "download ran — check the cache key and the download step.",
        )
    expected = expected.strip().lower()
    actual = sha256_file(path)
    if actual != expected:
        size_mb = path.stat().st_size // 1_048_576
        if delete_on_mismatch:
            path.unlink(missing_ok=True)
        raise SmokeFailure(
            FailureClass.CHECKSUM,
            f"SHA-256 drift on {path.name} ({size_mb} MB): registry expects "
            f"{expected}, on-disk bytes hash to {actual}"
            + (". The bad file was deleted." if delete_on_mismatch else ""),
        )
    print(f"  SHA-256 verified: {actual[:16]}… ({path.stat().st_size // 1_048_576} MB)")
    return actual


def download_model(url: str, sha256: str, model_id: str, models_dir: Path = MODELS_DIR) -> Path:
    dest = models_dir / f"{model_id}.gguf"
    if dest.exists():
        print(f"  Model already on disk: {dest}")
    else:
        _download_with_progress(url, dest)
    verify_model_checksum(dest, sha256)
    return dest


