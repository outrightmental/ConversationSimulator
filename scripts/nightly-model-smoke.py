class FailureClass:
    """Mutually exclusive failure classes, each with its own exit code."""

    BUDGET = "budget"
    DOWNLOAD = "download"
    CHECKSUM = "checksum"
    RUNTIME = "runtime"
    PIPELINE = "pipeline"
    TIMEOUT = "timeout"


EXIT_CODES = {
    FailureClass.BUDGET: 1,
    FailureClass.DOWNLOAD: 2,
    FailureClass.CHECKSUM: 3,
    FailureClass.RUNTIME: 4,
    FailureClass.PIPELINE: 5,
    FailureClass.TIMEOUT: 6,
}

